export const MUSCLE_BY_ID: Record<string, MuscleDef> = Object.fromEntries(
  MUSCLES.map((m) => [m.id, m]),
);

export const getMuscle = (id: string | null | undefined): MuscleDef | undefined =>
  id ? MUSCLE_BY_ID[id] : undefined;
