type OneSided = Omit<MuscleDef, 'side'>;

const negX = ([x, y, z]: Vec3): Vec3 => [-x, y, z];

const mirror = (def: OneSided): MuscleDef => ({
  ...def,
  id: `${def.id}-left`,
  side: 'left',
  origin: negX(def.origin),
  insertion: negX(def.insertion),
  path: def.path?.map(negX),
});

const asRight = (def: OneSided): MuscleDef => ({ ...def, id: `${def.id}-right`, side: 'right' });

